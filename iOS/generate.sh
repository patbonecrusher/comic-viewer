#!/bin/zsh
# Generates ComicViewerMobile.xcodeproj from project.yml. The signing team comes from
# ~/.config/mac-app-kit/defaults.env or ../.release.env (TEAM_ID) and is written to Local.xcconfig,
# which is git-ignored like the generated project.
set -euo pipefail
cd "$(dirname "$0")"
for f in "$HOME/.config/mac-app-kit/defaults.env" ../.release.env; do [[ -f $f ]] && source "$f"; done
print "// Generated by generate.sh. Not committed.\nDEVELOPMENT_TEAM = ${TEAM_ID:-}" > Local.xcconfig
xcodegen generate --quiet
echo "==> iOS/ComicViewerMobile.xcodeproj"
